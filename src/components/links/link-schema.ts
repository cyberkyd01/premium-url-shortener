import { z } from "zod";

/** Payload posted by the link editor (serialized as JSON in a hidden field). */
const urlRow = { url: z.string().min(1) };
export const linkPayloadSchema = z.object({
  url: z.string().min(1, "Destination URL is required"),
  alias: z.string().default(""),
  domainId: z.string().nullable().default(null),
  title: z.string().nullable().default(null),
  description: z.string().nullable().default(null),
  image: z.string().nullable().default(null),
  redirectType: z.string().default("direct"),
  splashId: z.string().nullable().default(null),
  overlayId: z.string().nullable().default(null),
  password: z.string().default(""),
  clearPassword: z.boolean().default(false),
  expiresAt: z.string().nullable().default(null),
  expiredUrl: z.string().nullable().default(null),
  clickLimit: z.number().nullable().default(null),
  clickLimitUrl: z.string().nullable().default(null),
  channelId: z.string().nullable().default(null),
  campaignId: z.string().nullable().default(null),
  pixelIds: z.array(z.string()).default([]),
  utm: z.record(z.string()).default({}),
  customParams: z.record(z.string()).default({}),
  forwardParams: z.boolean().default(false),
  geoTargets: z.array(z.object({ country: z.string(), state: z.string().optional(), ...urlRow })).default([]),
  deviceTargets: z.array(z.object({ device: z.string(), ...urlRow })).default([]),
  langTargets: z.array(z.object({ lang: z.string(), ...urlRow })).default([]),
  timeTargets: z.array(z.object({ from: z.string(), to: z.string(), days: z.array(z.number()).optional(), timezone: z.string().optional(), ...urlRow })).default([]),
  conditions: z.array(z.object({ match: z.enum(["all", "any"]), rules: z.array(z.object({ field: z.string(), op: z.string(), value: z.string() })), ...urlRow })).default([]),
  abUrls: z.array(z.object({ url: z.string(), weight: z.number().optional() })).default([]),
  rotatorMode: z.string().default("none"),
  deepLink: z.boolean().default(false),
  deepLinkConfig: z.object({ ios: z.string().optional(), android: z.string().optional(), fallback: z.string().optional(), auto: z.boolean().optional(), scheme: z.string().optional() }).default({}),
  cloaking: z.boolean().default(false),
  botBlock: z.boolean().default(false),
  inAppBreakout: z.boolean().default(false),
  isPublic: z.boolean().default(true),
  notes: z.string().nullable().default(null),
  tags: z.array(z.string()).default([]),
  activateAt: z.string().nullable().default(null),
  blockCountries: z.array(z.string()).default([]),
  blockIps: z.string().default(""),
  fallbackUrl: z.string().nullable().default(null),
  alertThreshold: z.number().nullable().default(null),
});
export type LinkPayload = z.infer<typeof linkPayloadSchema>;
